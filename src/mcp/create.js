export function openapiServer(name, spec, opts) {
  const { tools, skipped, baseUrl } = toolsFromOpenAPI(spec, opts)
  const src = `import { serve } from './mcp.js'

// Generated by \`jev mcp import\`. Configure with env vars / Worker secrets: API_BASE_URL, API_KEY
const BASE = ${JSON.stringify(baseUrl)}
const SPECS = ${JSON.stringify(tools.map(({ annotations, inputSchema, description, ...t }) => t))}

async function call(spec, args, env) {
  let path = spec.path
  const url = new URL((env.API_BASE_URL || BASE).replace(/\\/$/, '') + '/')
  const query = new URLSearchParams()
  for (const p of spec.params) {
    if (args[p.name] === undefined) continue
    if (p.in === 'path') path = path.replace(\`{\${p.name}}\`, encodeURIComponent(args[p.name]))
    else query.set(p.name, String(args[p.name]))
  }
  const target = new URL(path.replace(/^\\//, '') + (query.size ? '?' + query : ''), url)
  const headers = { accept: 'application/json', ...(env.API_KEY && { authorization: \`Bearer \${env.API_KEY}\` }) }
  if (spec.hasBody) headers['content-type'] = 'application/json'
  const res = await fetch(target, { method: spec.method, headers, body: spec.hasBody && args.body !== undefined ? JSON.stringify(args.body) : undefined })
  const text = await res.text()
  if (!res.ok) throw new Error(\`\${res.status}: \${text.slice(0, 2000)}\`)
  return text
}

const META = ${JSON.stringify(Object.fromEntries(tools.map(t => [t.name, { description: t.description, inputSchema: t.inputSchema, annotations: t.annotations }])), null, 2)}

export default serve({
  name: '${name}',
  version: '0.1.0',
  tools: SPECS.map(spec => ({ name: spec.name, ...META[spec.name], run: (args, env) => call(spec, args, env) })),
})
`
  return { src, tools, skipped }
}

export function scaffold(dir, name, serverSrc, { description = `${name} MCP server`, user = 'your-github-user' } = {}) {
  if (fs.existsSync(dir) && fs.readdirSync(dir).length) throw new Error(`${dir} is not empty`)
  fs.mkdirSync(dir, { recursive: true })
  const url = `https://${name}.<your-subdomain>.workers.dev/mcp`
  const files = {
    'server.js': serverSrc.replaceAll('__NAME__', name),
    'mcp.js': fs.readFileSync(RUNTIME, 'utf8'),
    'package.json': JSON.stringify({ name, version: '0.1.0', private: true, type: 'module', scripts: { dev: 'jev mcp dev', test: 'jev mcp test .', lint: 'jev mcp lint .', deploy: 'npx wrangler deploy' } }, null, 2) + '\n',
    'wrangler.toml': `name = "${name}"\nmain = "server.js"\ncompatibility_date = "2025-09-01"\n# Secrets: npx wrangler secret put API_KEY   |   npx wrangler secret put MCP_TOKEN (require auth)\n`,
    'server.json': JSON.stringify({
      $schema: 'https://static.modelcontextprotocol.io/schemas/2025-09-29/server.schema.json',
      name: `io.github.${user}/${name}`, description: description.slice(0, 100), version: '0.1.0',
      remotes: [{ type: 'streamable-http', url }],
    }, null, 2) + '\n',
    '.gitignore': 'node_modules\n.wrangler\n.dev.vars\n.env\n',
    'README.md': readme(name, description, url),
  }
  for (const [f, s] of Object.entries(files)) fs.writeFileSync(path.join(dir, f), s)
  return Object.keys(files)
}

